import { NextResponse } from "next/server";
import type { EmailOtpType } from "@supabase/supabase-js";
import { createClient } from "@/lib/supabase/server";
import { safeNext } from "@/lib/routes";

/**
 * Confirmación por token_hash (plantillas de correo personalizadas:
 * {{ .SiteURL }}/auth/confirm?token_hash={{ .TokenHash }}&type=signup&next=/panel/bienvenida).
 * Funciona aunque el enlace se abra en otro dispositivo.
 */
export async function GET(request: Request) {
  const url = new URL(request.url);
  const tokenHash = url.searchParams.get("token_hash");
  const type = url.searchParams.get("type") as EmailOtpType | null;
  const next = safeNext(url.searchParams.get("next"));
  if (tokenHash && type) {
    const supabase = await createClient();
    const { error } = await supabase.auth.verifyOtp({ type, token_hash: tokenHash });
    if (!error) return NextResponse.redirect(new URL(next, url.origin));
  }
  return NextResponse.redirect(new URL("/ingresar?error=enlace", url.origin));
}
